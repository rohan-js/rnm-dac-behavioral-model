#!/usr/bin/env python3
"""Generate ngspice benches for the 6-bit SKY130 resistor-string DAC.

Emits (into spice/):
  dac6_rstring_dc.sp    - DC bench TEMPLATE; gate V-source DC values carry
                          @GN<k>@ / @GP<k>@ placeholders filled per code by
                          tools/run_dc_sweep.py (one ngspice run per code)
  dac6_rstring_tran.sp  - code 0 -> 63 step at t=10 ns into a 1 pF load,
                          PWL gate sources (continuous ramp)
  dac6_mismatch.csv     - per-instance resistor mismatch draws (provenance)

Determinism: mismatch draws use random.Random(42) (same seeded discipline as
the owner's EKF project); the CSV is committed so benches are bit-reproducible.

Design notes (all empirical, ngspice-47):
  - Gate logic via B sources (==, floor(), even smooth Gaussians of v(cs))
    breaks OP convergence on this network; the identical network with fixed
    V-source gates converges. Hence: plain V gates, driven by the runner.
  - The 64 TG switches are X-instances of the PDK wrapper subckts
    sky130_fd_pr__nfet_01v8 / sky130_fd_pr__pfet_01v8 (internal M auto-bins).
  - Per-instance mismatch = rsheet override on the resistor body.

Run benches with CWD = spice/ (include paths are relative to it).
"""
import random
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SPICE = REPO / "spice"

NBITS = 6
NCODES = 1 << NBITS
VREF = 3.3
RSHEET = 317.3885          # res_high_po body sheet resistance (ohm/sq)
MISMATCH_FRAC = 0.005      # +/- 0.5% per-instance body sheet variation
SEED = 42
TG_W, TG_L = "1.1u", "0.16u"

PARAMS = """\
.param sky130_fd_pr__res_high_po__var = 0
.param sky130_fd_pr__res_high_po__slope_spectre = 0
.param sky130_fd_pr__res_high_po__con_slope_spectre = 0
.param tc1rpolybody = 0
.param tc2rpolybody = 0
.param sky130_fd_pr__pfet_01v8__wlod_diff = 0
.param sky130_fd_pr__pfet_01v8__kvth0_diff = 0
.param sky130_fd_pr__pfet_01v8__lkvth0_diff = 0
.param sky130_fd_pr__pfet_01v8__wkvth0_diff = 0
.param sky130_fd_pr__pfet_01v8__ku0_diff = 0
.param sky130_fd_pr__pfet_01v8__lku0_diff = 0
.param sky130_fd_pr__pfet_01v8__wku0_diff = 0
.param sky130_fd_pr__pfet_01v8__kvsat_diff = 0
"""

INCLUDES = """\
.include "models/sky130/sky130_fd_pr__nfet_01v8__tt.corner.spice"
.include "models/sky130/sky130_fd_pr__nfet_01v8__mismatch.corner.spice"
.include "models/sky130/sky130_fd_pr__pfet_01v8__tt.corner.spice"
.include "models/sky130/sky130_fd_pr__pfet_01v8__mismatch.corner.spice"
.include "models/sky130/sky130_fd_pr__res_high_po.model.spice"
.include "models/sky130/parasitic_res_po_stub.sp"
"""


def ladder_and_switches():
    """Ladder resistors (with mismatch draws) + 64 TG switches.

    Tap mapping: code k connects out to node n(64-k); n64 is ground, so
    code 0 -> 0 V and code 63 -> n1 = Vref*63/64.
    """
    rng = random.Random(SEED)
    lines = []
    mismatches = []
    for k in range(NCODES):
        m = rng.uniform(-MISMATCH_FRAC, MISMATCH_FRAC)
        mismatches.append(m)
        a = "vref" if k == 0 else f"n{k}"
        b = "0" if k == NCODES - 1 else f"n{k+1}"
        lines.append(
            f"Xr{k} {a} {b} 0 sky130_fd_pr__res_high_po w=1 l=1 "
            f"rsheet={{rsheet_body*(1{m:+.6f})}}"
        )
    lines.append(".param rsheet_body = %s" % RSHEET)
    for k in range(NCODES):
        tap = "0" if k == 0 else f"n{NCODES - k}"
        lines.append(f"Vgn{k} gn{k} 0 DC @GN{k}@")
        lines.append(f"Vgp{k} gp{k} 0 DC @GP{k}@")
        lines.append(
            f"Xntg{k} out gn{k} {tap} 0 sky130_fd_pr__nfet_01v8 w={TG_W} l={TG_L}"
        )
        lines.append(
            f"Xptg{k} out gp{k} {tap} vref sky130_fd_pr__pfet_01v8 w={TG_W} l={TG_L}"
        )
    return lines, mismatches


def fill_gates(lines, code):
    """Replace gate placeholders with the on/off configuration for `code`."""
    out = []
    for ln in lines:
        if "@GN" in ln or "@GP" in ln:
            k = int(ln.split("@")[1][2:])
            nfet_on = (k == code)
            ln = ln.replace(f"@GN{k}@", f"{VREF if nfet_on else 0:.6f}")
            ln = ln.replace(f"@GP{k}@", f"{VREF if not nfet_on else 0:.6f}")
        out.append(ln)
    return out


def write_dc_template(body_lines):
    text = (
        "* 6-bit SKY130 R-string DAC - DC bench TEMPLATE (one run per code)\n"
        "* generated by tools/gen_dac_netlist.py; @GN<k>@/@GP<k>@ placeholders\n"
        "* are filled by tools/run_dc_sweep.py\n"
        + PARAMS + "\n" + INCLUDES + "\n"
        + f"Vvref vref 0 DC {VREF}\n"
        + "\n".join(body_lines) + "\n\n"
        + ".control\n"
        + "  op\n"
        + "  print col v(out) > raw/dac6_last.txt\n"
        + "quit\n"
        + ".endc\n"
        + ".end\n"
    )
    (SPICE / "dac6_rstring_dc.sp").write_text(text, encoding="utf-8", newline="\n")


def write_tran(body_lines):
    """Settling bench: all gates PWL, code 0 until 10 ns, code 63 after 10.2 ns."""
    t0, t1 = "10n", "10.2n"
    lines = []
    for ln in body_lines:
        if "@GN" in ln:
            k = int(ln.split("@")[1][2:])
            # switch 63 turns ON at the step; every other switch turns OFF
            if k == NCODES - 1:
                lines.append(f"Vgn{k} gn{k} 0 PWL(0 0 {t0} 0 {t1} {VREF})")
            else:
                lines.append(f"Vgn{k} gn{k} 0 PWL(0 {VREF} {t0} {VREF} {t1} 0)")
        elif "@GP" in ln:
            k = int(ln.split("@")[1][2:])
            if k == NCODES - 1:
                lines.append(f"Vgp{k} gp{k} 0 PWL(0 {VREF} {t0} {VREF} {t1} 0)")
            else:
                lines.append(f"Vgp{k} gp{k} 0 PWL(0 0 {t0} 0 {t1} {VREF})")
        else:
            lines.append(ln)
    text = (
        f"* 6-bit SKY130 R-string DAC - settling bench, code 0 -> {NCODES-1} at {t0}\n"
        f"* generated by tools/gen_dac_netlist.py; load CL = 1 pF\n"
        + PARAMS + "\n" + INCLUDES + "\n"
        + f"Vvref vref 0 DC {VREF}\n"
        + "\n".join(lines) + "\n"
        + "CL out 0 1p\n\n"
        + ".control\n"
        + "  save v(out)\n"
        + "  tran 10n 60u\n"
        + "  wrdata raw/dac6_tran.csv v(out)\n"
        + "quit\n"
        + ".endc\n"
        + ".end\n"
    )
    (SPICE / "dac6_rstring_tran.sp").write_text(text, encoding="utf-8", newline="\n")


def main():
    SPICE.mkdir(exist_ok=True)
    (SPICE / "raw").mkdir(exist_ok=True)
    body, mism = ladder_and_switches()
    write_dc_template(body)
    write_tran(body)
    with open(SPICE / "dac6_mismatch.csv", "w", newline="\n") as f:
        f.write("index,rsheet_mult\n")
        for i, m in enumerate(mism):
            f.write(f"{i},{m:+.6f}\n")
    print(f"generated: dc template, tran bench, "
          f"{NCODES} mismatch draws (seed {SEED}, +/-{MISMATCH_FRAC*100:.1f}%)")


if __name__ == "__main__":
    main()
