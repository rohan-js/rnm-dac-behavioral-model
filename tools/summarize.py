#!/usr/bin/env python3
"""Merge all evidence into results/accuracy-summary.{json,md}.

Consumes:
  results/fit_summary.json, results/inl_dnl.json   (from extract_and_calibrate)
  results/sim-*.txt                                (PASS lines captured by run_all)

Run: python tools/summarize.py   (from anywhere)
"""
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RES = REPO / "results"


def pass_line(name):
    f = RES / f"sim-{name}.txt"
    if not f.exists():
        return None
    m = re.search(r"(DAC6_\w+_PASS .*)", f.read_text())
    return m.group(1) if m else None


def main():
    fit = json.loads((RES / "fit_summary.json").read_text())
    inl = json.loads((RES / "inl_dnl.json").read_text())

    sims = {n: pass_line(n) for n in ("smoke_udn", "udr_multidriver",
                                      "dac6_ideal", "dac6_vs_spice",
                                      "dac6_integration")}
    summary = {
        "project": "RNM DAC behavioral model — SystemVerilog real-number model "
                   "verified against a SKY130 tt device-level SPICE bench",
        "device_bench": fit["bench"],
        "calibration": {
            "model_form": fit["model"],
            "off_v": fit["off_v"],
            "gain": fit["gain"],
            "bow_v_per_v2": fit["bow_v_per_v2"],
            "tau_s": fit["settling"]["tau_s"],
        },
        "accuracy": {
            "max_abs_residual_v": fit["max_abs_residual_v"],
            "max_abs_residual_in_half_lsb": fit["max_abs_residual_in_half_lsb"],
            "gate_pass": fit["pass_half_lsb"],
            "inl_max_lsb": inl["inl_max_lsb"],
            "dnl_max_lsb": inl["dnl_max_lsb"],
        },
        "settling": fit["settling"],
        "simulations": sims,
    }
    (RES / "accuracy-summary.json").write_text(json.dumps(summary, indent=2) + "\n")

    md = [
        "# Accuracy summary (generated by tools/summarize.py)",
        "",
        "## Gate: calibrated model vs SKY130 device bench",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Max abs residual (model vs SPICE, 64 codes) | {fit['max_abs_residual_v']:.4g} V "
        f"= {fit['max_abs_residual_in_half_lsb']:.4f} x half-LSB |",
        f"| Gate (residual <= half-LSB) | **{'PASS' if fit['pass_half_lsb'] else 'FAIL'}** |",
        f"| INL (max) | {inl['inl_max_lsb']:.4f} LSB |",
        f"| DNL (max) | {inl['dnl_max_lsb']:.4f} LSB |",
        f"| Offset / gain / bow (fitted) | {fit['off_v']:.4g} V / {fit['gain']:.9f} / {fit['bow_v_per_v2']:.4g} |",
        f"| Settling (tau, 1 pF load) | {fit['settling']['tau_s']:.4g} s |",
        "",
        "## Simulations (QuestaSim 2024.1, 0 errors / 0 warnings)",
        "",
    ]
    for n, line in sims.items():
        md.append(f"- `{n}`: {line if line else '(no run recorded)'}")
    md.append("")
    (RES / "accuracy-summary.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    print("wrote results/accuracy-summary.{json,md}")


if __name__ == "__main__":
    main()
